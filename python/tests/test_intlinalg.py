import random

import pytest
import sympy as sp

from nondim.intlinalg import (all_column_bases, independent_columns, int_row_echelon, left_inverse_on_columns,
                              left_kernel_basis, rank, right_inverse, right_kernel_basis)


def random_matrices(n=60, seed=0):
    rng = random.Random(seed)
    for _ in range(n):
        m, k = rng.randint(1, 6), rng.randint(1, 6)
        M = sp.Matrix(m, k, lambda i, j: rng.randint(-4, 4))
        if rng.random() < 0.4 and m > 1:  # force rank deficiency sometimes
            M[m - 1, :] = 2 * M[0, :]
        yield M


@pytest.mark.parametrize("M", list(random_matrices()))
def test_echelon_properties(M):
    U, H, piv = int_row_echelon(M)
    assert U * M == H
    assert abs(U.det()) == 1, "U must be unimodular"
    assert len(piv) == M.rank()
    assert piv == sorted(piv)
    for row, col in enumerate(piv):
        assert H[row, col] > 0
        assert all(H[i, col] == 0 for i in range(row + 1, H.shape[0]))
        assert all(H[row, j] == 0 for j in range(col)), "pivot is the first nonzero in its row"
        assert all(0 <= H[i, col] < H[row, col] for i in range(row)), "entries above a pivot are reduced"
    assert all(x == 0 for x in H[len(piv):, :])


@pytest.mark.parametrize("M", list(random_matrices(40, seed=1)))
def test_kernels_are_exact_and_complete(M):
    L = left_kernel_basis(M)
    assert L.shape == (M.shape[0] - M.rank(), M.shape[0])
    assert L * M == sp.zeros(L.shape[0], M.shape[1])
    assert L.shape[0] == 0 or L.rank() == L.shape[0]
    R = right_kernel_basis(M)
    assert R.shape == (M.shape[1], M.shape[1] - M.rank())
    assert M * R == sp.zeros(M.shape[0], R.shape[1])


def test_kernel_basis_is_a_lattice_basis_not_just_a_rational_one():
    # The integer kernel of [2, 4] is generated by (2, -1)... as a row: (-2, 1) or (2, -1), never (4, -2).
    L = left_kernel_basis(sp.Matrix([[2], [4]]))
    assert L.shape == (1, 2) and sp.gcd(L[0, 0], L[0, 1]) == 1


def test_echelon_rejects_non_integers():
    with pytest.raises(ValueError):
        int_row_echelon(sp.Matrix([[sp.Rational(1, 2)]]))


def test_empty_and_zero_matrices():
    assert left_kernel_basis(sp.zeros(3, 2)) .shape == (3, 3)
    assert rank(sp.zeros(2, 2)) == 0


@pytest.mark.parametrize("M", list(random_matrices(30, seed=2)))
def test_independent_columns_is_a_maximal_independent_set(M):
    cols = independent_columns(M)
    assert len(cols) == M.rank()
    assert M[:, cols].rank() == len(cols)
    bases = all_column_bases(M, range(M.shape[1]), M.rank())
    assert tuple(cols) in bases
    assert all(M[:, list(b)].rank() == M.rank() for b in bases)


def test_independent_columns_respects_order():
    M = sp.Matrix([[1, 1, 0], [0, 0, 1]])
    assert independent_columns(M, [1, 0, 2]) == [1, 2]


def test_inverse_certificates():
    M = sp.Matrix([[1, 0, 2], [0, 1, 3]])
    assert M * right_inverse(M) == sp.eye(2)
    assert left_inverse_on_columns(M, [0, 1]) * M[:, [0, 1]] == sp.eye(2)
