"""Lean certificates in the general form: the reduction theorem applied to one model.

Input: an `HLReduction` (from desr or from this package's solver). Output: a Lean file
whose theorems Lean proves by computation plus the general theory in `lean/NondimVerify`:

    sys                    the model as Lean data (terms with coefficients and exponents)
    eq_<state>             ...and a proof that this data is the equation you wrote
    symmetry               the tool's scalings are symmetries of sys            [decide]
    unimodular, invariant, auxiliaries_free, auxiliaries_are_parameters         [decide]
    reduced_identity_<s>   the algebra behind the tool's reduced equation for the state s
    reduction_correct      along every positive solution, the tool's new variables satisfy the
                           tool's reduced equations in the tool's new time
    cross_section          the same solution, rescaled, has every auxiliary monomial equal to 1
    invariants_complete    Buckingham Pi: anything unit-independent is a function of the invariants
    maximal                no scaling symmetry was missed (cross-check against our own K)

Compared with `lean_export.py` (matrix-level certificates), nothing here depends on an
exponent matrix supplied from outside for the symmetry and solution statements: Lean reads
the symmetry condition off `sys` itself.
"""

from __future__ import annotations

from pathlib import Path

import sympy as sp

from .hlform import HLReduction
from .lean_export import lean_matrix, lean_name, to_lean


def _coeff(c: sp.Rational) -> str:
    c = sp.Rational(c)
    if c.q == 1:
        return f"({c.p})" if c.p < 0 else str(c.p)
    return f"({c.p} / {c.q})"


def _vec(xs) -> str:
    return "![" + ", ".join(str(int(x)) for x in xs) + "]"


def _mat(name: str, M: sp.Matrix, doc: str) -> list[str]:
    r, c = M.shape
    return [f"/-- {doc} -/", f"def {name} : Matrix (Fin {r}) (Fin {c}) ℤ :=\n  {lean_matrix(M)}", ""]


def _module(name: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in name.replace("-", "_").split("_"))


def certificate(red: HLReduction, module: str | None = None) -> str:
    red.check()
    m = red.model
    n, r, k, mm = red.n, red.r, red.Vi.shape[1], red.Vn.shape[1]
    module = module or _module(m.name)
    V = red.variables
    idx = {v: i for i, v in enumerate(V)}
    terms = red.terms()
    pi = [sp.Symbol(f"(π {j})", positive=True) for j in range(mm)]
    to_pi = dict(zip(red.invariant_symbols, pi))
    args = " ".join(lean_name(v) for v in V)
    point = "![" + ", ".join(lean_name(v) for v in V) + "]"
    unfold = "LaurentSystem.rhs, Term.eval, monomial, sys, Fin.prod_univ_succ"

    doc = [
        f"# `{m.name}`, reduced by {red.source}, checked against the general theory",
        "",
        "Auto-generated by `nondim certify`. Do not edit: change the model and regenerate.",
        "",
        "Variables (Lean index order): " + ", ".join(f"{i} = {v}" for i, v in enumerate(V)),
        "",
        "Equations:",
        *[f"    d{z}/d{m.t} = {f}" for z, f in zip(m.states, m.rhs)],
        "",
        f"New time: {red.time_invariant}",
        "Invariants (the new variables):",
        *[f"    π {j} = {s} = {mono}" for j, (s, mono) in enumerate(zip(red.invariant_symbols, red.invariant_monomials()))],
        "Auxiliary monomials (set to 1): " + ", ".join(map(str, red.auxiliary_monomials())),
        "",
        "Reduced equations (ν = the new variable for each state, τ = the new time):",
        *[f"    d{red.invariant_symbols[red.state_col[z]]}/dτ = {red.reduced_rhs[z]}" for z in m.states],
        "",
        f"Parameters: {len(red.parameters)} -> {len(red.reduced_parameters())}",
    ]
    out = [
        "import NondimVerify.Reduction",
        "import NondimVerify.Theory",
        "",
        "/-!", *doc, "-/",
        "",
        "-- generated proofs end with `try (...)`: sometimes `simp` has already finished the goal",
        "set_option linter.unusedVariables false",
        "set_option linter.unusedTactic false",
        "set_option linter.unreachableTactic false",
        "",
        f"namespace NondimVerify.Certified.{module}",
        "",
        "open NondimVerify Matrix",
        "",
        "/-! ## The model as data, and a check that the data is the model -/",
        "",
        "/-- One list of terms `coefficient * ∏ x_j ^ e_j` per variable; parameters have none. -/",
        f"noncomputable def sys : LaurentSystem {n} where",
        "  terms := ![" + ",\n    ".join(
            "[" + ", ".join(f"⟨{_coeff(c)}, {_vec(e)}⟩" for c, e in ts) + "]" for ts in terms) + "]",
        "",
    ]
    for z, f in zip(m.states, m.rhs):
        out += [
            f"/-- The data for `{z}` is the equation `d{z}/d{m.t} = {f}`. -/",
            f"theorem eq_{lean_name(z)} ({args} : ℝ) :\n    sys.rhs {idx[z]} {point} = {to_lean(f)} := by\n"
            f"  simp [{unfold}]\n  try (first | ring1 | (field_simp; ring1) | field_simp)",
            "",
        ]

    out += ["/-! ## The scalings are symmetries -/", ""]
    out += _mat("A", red.A, "Weights of the variables under each scaling (one scaling per row).")
    out += [
        "/-- Weight of time under each scaling. -/",
        f"def tau : Fin {r} → ℤ := {_vec(red.tau)}",
        "",
        "/-- Every term of every equation has the weight of its left-hand side: Lean reads this off",
        "`sys`, with no exponent matrix supplied from outside. -/",
        "theorem symmetry : sys.IsSymmetry A tau := by decide +kernel",
        "",
        "/-! ## The change of variables -/",
        "",
    ]
    out += _mat("Vi", red.Vi, "Auxiliary monomials (columns): the reduction sets these to 1.")
    out += _mat("Vn", red.Vn, "Invariants (columns): the new variables.")
    out += _mat("Wu", red.Wu, "Top rows of the inverse of `[Vi | Vn]`.")
    out += _mat("Wd", red.Wd, "Bottom rows of the inverse of `[Vi | Vn]`: how to recover the variables from the invariants.")
    out += _mat("G", red.G, "Left inverse of `A * Vi`, up to the factor `d`.")
    out += [
        "/-- `[Vi | Vn]` is unimodular with inverse `[Wu ; Wd]`. -/",
        "theorem unimodular : Vi * Wu + Vn * Wd = 1 := by decide +kernel",
        "",
        "/-- Every new variable is invariant under every scaling: it is dimensionless. -/",
        "theorem invariant : A * Vn = 0 := by decide +kernel",
        "",
        "/-- The auxiliary monomials can be scaled to any positive values, in particular to 1. -/",
        f"theorem auxiliaries_free : G * (A * Vi) = ({red.d} : ℤ) • (1 : Matrix (Fin {k}) (Fin {k}) ℤ) := by",
        "  decide +kernel",
        "",
        "/-- The auxiliary monomials involve parameters only, so they are constant along solutions. -/",
        "theorem auxiliaries_are_parameters : sys.OnlyParams Vi := by decide +kernel",
        "",
        "/-! ## The reduced equations -/",
        "",
    ]
    T = red.time_factor()
    nonzero = "".join(f"\n  have h{j} := (hz {j}).ne'" for j in range(n))
    out[-2:] = [
        "/-! ## The reduced equations",
        "",
        f"New time: `τ = ({T}) * {m.t}`. Each state `z` gets the new variable `ν = z * (parameters)`.",
        "For each one, a single algebraic identity says that the tool's reduced equation is right.",
        "-/",
        "",
        f"/-- Exponents of the factor `{T}` between the old and the new time. -/",
        f"def w : Fin {n} → ℤ := {_vec(red.time_exponents)}",
        "",
        "/-- The time factor involves parameters only, so it is constant along solutions. -/",
        "theorem time_factor_is_parameters : sys.ParamMonomial w := by decide +kernel",
        "",
    ]
    for z in m.states:
        g = red.reduced_rhs[z].xreplace(to_pi)
        zn, j = lean_name(z), red.state_col[z]
        u = red.state_factor_exponents(z)
        c = sp.Mul(*[v ** e for v, e in zip(V, u)])
        out += [
            f"/-- Exponents of the factor in `{red.invariant_symbols[j]} = {z} * ({c})`. -/",
            f"def u_{zn} : Fin {n} → ℤ := {_vec(u)}",
            "",
            f"/-- The new variable for `{z}` (column {j} of `Vn`) is `{z}` times that factor... -/",
            f"theorem new_{zn}_eq : (fun i => Vn i {j}) = u_{zn} + fun j => if j = {idx[z]} then 1 else 0 := by\n"
            f"  decide +kernel",
            "",
            "/-- ...and the factor involves parameters only. -/",
            f"theorem factor_{zn}_is_parameters : sys.ParamMonomial u_{zn} := by decide +kernel",
            "",
            f"/-- Reduced right-hand side for `{z}`, as reported by {red.source}: `{red.reduced_rhs[z]}`. -/",
            f"noncomputable def red_{zn} (π : Fin {mm} → ℝ) : ℝ := {to_lean(g)}",
            "",
            f"/-- `({c}) * (d{z}/d{m.t})  =  ({T}) * (reduced right-hand side at the invariants)`,",
            "at every positive point. -/",
            f"theorem reduced_identity_{zn} (z : Fin {n} → ℝ) (hz : ∀ j, 0 < z j) :\n"
            f"    monomial z u_{zn} * sys.rhs {idx[z]} z = monomial z w * red_{zn} (piGroups Vn z) := by{nonzero}\n"
            f"  simp [{unfold}, piGroups, Vn, u_{zn}, w, red_{zn}]\n"
            f"  try (first | ring1 | (field_simp; ring1) | field_simp)",
            "",
        ]

    def stmt(z):
        return (f"HasDerivAt (fun τ => piGroups Vn (x (τ / monomial (x 0) w)) {red.state_col[z]})\n"
                f"        (red_{lean_name(z)} (piGroups Vn (x (τ / monomial (x 0) w)))) τ")

    def proof(z):
        zn = lean_name(z)
        return (f"hx.hasDerivAt_newVariable hpos {idx[z]} _ u_{zn} w new_{zn}_eq factor_{zn}_is_parameters\n"
                f"      time_factor_is_parameters (fun z => red_{zn} (piGroups Vn z)) reduced_identity_{zn} τ")

    conj = " ∧\n      ".join(stmt(z) for z in m.states)
    proofs = ",\n    ".join(proof(z) for z in m.states)
    proofs = f"⟨{proofs}⟩" if len(m.states) > 1 else proofs
    out += [
        "/-! ## The reduction is correct -/",
        "",
        "/-- **Main statement.** Take any solution of the model with positive values and follow the new",
        f"variables (the invariants `piGroups Vn`) in the new time `τ = ({T}) * {m.t}`. They satisfy the",
        f"reduced equations reported by {red.source}. -/",
        f"theorem reduction_correct {{x : ℝ → Fin {n} → ℝ}} (hx : sys.IsSolution x) (hpos : ∀ s i, 0 < x s i)\n"
        f"    (τ : ℝ) :\n"
        f"      {conj} :=\n"
        f"  {proofs}",
        "",
        "/-- **The same solution on the cross-section.** Rescaling by a symmetry turns any positive",
        "solution into a solution of the same equations in which every auxiliary monomial equals 1.",
        "The rescaled solution has the same invariants and is determined by them. -/",
        f"theorem cross_section {{x : ℝ → Fin {n} → ℝ}} (hx : sys.IsSolution x) (hpos : ∀ s i, 0 < x s i) :\n"
        f"    ∃ lam : Fin {r} → ℝ, (∀ j, 0 < lam j) ∧\n"
        f"      sys.IsSolution (fun s => scale A lam (x (s / timeFactor lam tau))) ∧\n"
        f"      (∀ s, piGroups Vn (scale A lam (x (s / timeFactor lam tau)))\n"
        f"        = piGroups Vn (x (s / timeFactor lam tau))) ∧\n"
        f"      ∀ s, scale A lam (x (s / timeFactor lam tau))\n"
        f"        = reconstruct Wd (piGroups Vn (scale A lam (x (s / timeFactor lam tau)))) := by\n"
        f"  obtain ⟨lam, hlam, hsol, -, hinv, hsec⟩ :=\n"
        f"    symmetry.reduction_of_parameters Vi Vn Wu Wd unimodular invariant G ({red.d})\n"
        f"      (by decide) auxiliaries_free auxiliaries_are_parameters hx hpos\n"
        f"  exact ⟨lam, hlam, hsol, hinv, hsec⟩",
        "",
    ]

    if red.Dfull is not None:
        N = n + 1
        out += [
            "/-! ## Buckingham Pi for this model",
            "",
            "Same matrices with time included. Order: " + ", ".join(map(str, red.full_order)) + ".",
            "-/",
            "",
        ]
        out += _mat("Dfull", red.Dfull, "All scalings, acting on time and the variables.")
        out += _mat("Pfull", red.Pfull, "All invariants, including the new time.")
        out += _mat("V1full", red.V1full, "Auxiliary columns.")
        out += _mat("W1full", red.W1full, "Top rows of the inverse.")
        out += _mat("W2full", red.W2full, "Bottom rows of the inverse.")
        out += [
            "/-- **The invariants are complete.** Any quantity built from time, the states and the",
            "parameters that does not depend on the choice of units is a function of the invariants. -/",
            f"theorem invariants_complete {{α : Type}} (f : (Fin {N} → ℝ) → α) (hf : UnitInvariant Dfull f)\n"
            f"    (q q' : Fin {N} → ℝ) (hq : ∀ i, 0 < q i) (hq' : ∀ i, 0 < q' i)\n"
            f"    (h : piGroups Pfull q = piGroups Pfull q') : f q = f q' :=\n"
            f"  buckingham_pi Dfull Pfull\n"
            f"    (spans_kernel_of_certificate Dfull Pfull V1full W1full W2full G ({red.d}) (by decide)\n"
            f"      (by decide +kernel) (by decide +kernel) (by decide +kernel))\n"
            f"    f hf q q' hq hq' h",
            "",
        ]

    K = red.independent_K()
    F = red.full_scaling_matrix()
    if K.shape[1] and red.is_maximal():
        out += [
            "/-! ## No scaling was missed",
            "",
            "Cross-check against an exponent matrix derived independently by this package",
            "(rows: time, then the variables).",
            "-/",
            "",
        ]
        out += _mat("Kmat", K, "Exponent matrix: every scaling must kill every column.")
        out += _mat("Afull", F, "`[tau | A]`: the scalings with the weight of time in front.")
        out += [
            "theorem kills_K : Afull * Kmat = 0 := by decide +kernel",
            "",
            f"theorem rank_K : Kmat.rank = {K.rank()} := by unfold Kmat; eval_rank",
            "",
            f"/-- {r} independent scalings out of {n + 1} - {K.rank()} = {n + 1 - K.rank()} possible: none is missing. -/",
            f"theorem rank_A : Afull.rank = {r} := by unfold Afull; eval_rank",
            "",
        ]
    out += [f"end NondimVerify.Certified.{module}", ""]
    return "\n".join(out)


def write_certificate(red: HLReduction, path: Path, module: str | None = None) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(certificate(red, module))
    return path
