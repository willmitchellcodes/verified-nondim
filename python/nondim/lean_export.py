"""Turn a Nondimensionalization into a Lean 4 certificate file.

Python is the *untrusted solver*. Everything it claims is restated as a Lean
theorem and re-proved there by small, trusted checks:

  * integer matrix identities (A * K = 0, ...)   -> `decide +kernel`
  * ranks of integer matrices                    -> Mathlib's `eval_rank`
  * the chain-rule identity for each equation    -> `field_simp` + `ring`

If the solver has a bug, `lake build` fails. Keep this file small and readable:
it is part of the trusted computing base (a mistranscribed equation would be
"verified as stated").
"""

from __future__ import annotations

from dataclasses import dataclass
from functools import reduce
from pathlib import Path

import sympy as sp

from .constraints import ConstraintResult
from .scaling import Nondimensionalization


class LeanExportError(ValueError):
    pass


# ---------------------------------------------------------------- printing


def lean_matrix(M: sp.Matrix) -> str:
    if M.shape[0] == 0 or M.shape[1] == 0:
        raise LeanExportError("Lean certificate matrices must be non-empty")
    rows = [", ".join(str(int(x)) for x in M.row(i)) for i in range(M.shape[0])]
    pad = " " * 4
    return "!![" + (";\n" + pad).join(rows) + "]"


def lean_fin_vec(idxs: list[int]) -> str:
    return "![" + ", ".join(map(str, idxs)) + "]"


def to_lean(e: sp.Expr) -> str:
    """Print a rational function of symbols as a Lean real-number expression."""
    e = sp.sympify(e)
    if e.is_Symbol:
        return lean_name(e)
    if e.is_Integer:
        return f"({e})" if e < 0 else str(e)
    if e.is_Rational:
        return f"({e.p} / {e.q} : ℝ)"
    if e.is_Add:
        return "(" + " + ".join(to_lean(a) for a in e.args) + ")"
    if e.is_Mul:
        coeff, rest = e.as_coeff_Mul()
        num, den = [], []
        for f in sp.Mul.make_args(rest):
            if f.is_Pow and f.exp.is_Integer and f.exp < 0:
                den.append(f.base ** (-f.exp))
            else:
                num.append(f)
        if coeff.is_Rational and coeff.q != 1:
            num.insert(0, sp.Integer(coeff.p))
            den.insert(0, sp.Integer(coeff.q))
        elif coeff != 1:
            num.insert(0, coeff)
        num_s = " * ".join(to_lean(f) for f in num) if num else "1"
        if not den:
            return f"({num_s})"
        return f"({num_s} / ({' * '.join(to_lean(f) for f in den)}))"
    if e.is_Pow:
        if e.exp.is_Integer and e.exp > 0:
            return f"({to_lean(e.base)} ^ {e.exp})"
        if e.exp == -1:
            return f"(1 / {to_lean(e.base)})"
        if e.exp.is_Integer and e.exp < 0:
            return f"(1 / {to_lean(e.base)} ^ {-e.exp})"
        raise LeanExportError(f"non-integer power {e}: needs Real.rpow, not exported")
    raise LeanExportError(f"cannot print {e} ({type(e).__name__}) to Lean")


# ---------------------------------------------------------------- pieces


def _integer_columns(vectors: list[list[sp.Rational]]) -> sp.Matrix:
    """Stack rational exponent vectors as columns, clearing denominators per column."""
    cols = []
    for v in vectors:
        den = reduce(sp.ilcm, [sp.Rational(x).q for x in v], 1)
        cols.append([sp.Integer(x * den) for x in v])
    return sp.Matrix(cols).T


@dataclass
class Section:
    title: str
    body: str


def _module_name(model_name: str) -> str:
    return "".join(
        part[:1].upper() + part[1:] for part in model_name.replace("-", "_").split("_")
    )


def certificate(
    nd: Nondimensionalization,
    constraints: list[ConstraintResult] = (),
    module: str | None = None,
) -> str:
    m = nd.model
    an = nd.analysis
    V = m.variables
    n, r = len(V), an.A.shape[0]
    module = module or _module_name(m.name)
    p_idx = [m.index(p) for p in m.params]
    S_idx = [m.index(s) for s in nd.normalized]
    new_vars = [x for x in V if x not in nd.normalized]

    doc = [
        f"# Certificate for `{m.name}`",
        "",
        "Auto-generated by `python/run_all.py` from the untrusted Python solver.",
        "Do not edit by hand: change the model in Python and regenerate.",
        "",
        "Variables (column order): " + ", ".join(map(str, V)),
        "",
        "Model:",
        *[f"    d{z}/d{m.t} = {f}" for z, f in zip(m.states, m.rhs)],
    ]
    if m.extra_invariants:
        doc.append(
            "Extra invariants (initial conditions / unit links): "
            + ", ".join(map(str, m.extra_invariants))
        )
    doc += [
        "",
        "Normalized to 1: " + (", ".join(map(str, nd.normalized)) or "(none)"),
        "New variables:",
        *[f"    {nd.new_symbol[x]} = {nd.new_expr[x]}" for x in new_vars],
        "Reduced system:",
        *[
            f"    d{nd.new_symbol[z]}/d{nd.new_symbol[m.t]} = {g}"
            for z, g in zip(m.states, nd.reduced_rhs)
        ],
        "",
        f"Parameters: {len(m.params)} -> {len(nd.reduced_params)}",
    ]

    out = [
        "import NondimVerify.Basic",
        "",
        "/-!",
        *doc,
        "-/",
        "",
        "-- Positivity hypotheses are stated for every variable, whether or not a proof needs them.",
        "set_option linter.unusedVariables false",
        "",
        f"namespace NondimVerify.Cert.{module}",
        "",
        "/-- Exponent matrix `K`: each column is a monomial that every scaling symmetry must fix. -/",
        f"def Kmat : Matrix (Fin {n}) (Fin {an.K.shape[1]}) ℤ :=\n  {lean_matrix(an.K)}",
        "",
        "/-- Maximal scaling matrix `A`: each row is one independent scaling symmetry. -/",
        f"def Amat : Matrix (Fin {r}) (Fin {n}) ℤ :=\n  {lean_matrix(an.A)}",
        "",
        "/-- **Check 1.** Every row of `A` is a symmetry of the equations (`A * K = 0`). -/",
        "theorem symmetries : Amat * Kmat = 0 := by decide +kernel",
        "",
        f"/-- **Check 2.** `rank K = {an.rank_K}`, so the space of scalings has dimension",
        f"`{n} - {an.rank_K} = {n - an.rank_K}` (rank-nullity). -/",
        f"theorem rank_K : Kmat.rank = {an.rank_K} := by unfold Kmat; eval_rank",
        "",
        f"/-- **Check 3.** The {r} rows of `A` are independent. With Check 2 this means `A` captures",
        "*every* scaling symmetry, so no cleverer scaling can remove more parameters",
        "(see `NondimVerify.maximal_of_rank` in `Theory.lean`). -/",
        f"theorem rank_A : Amat.rank = {r} := by unfold Amat; eval_rank",
        "",
    ]

    Apar = an.A[:, p_idx]
    out += [
        "/-- Columns of `A` belonging to the parameters "
        + ", ".join(map(str, m.params))
        + ". -/",
        f"def Apar : Matrix (Fin {r}) (Fin {len(p_idx)}) ℤ :=\n  {lean_matrix(Apar)}",
        "",
        f"theorem Apar_cols : Apar = Amat.submatrix id {lean_fin_vec(p_idx)} := by decide +kernel",
        "",
        f"/-- **Check 4.** At most `rank Apar = {an.param_rank}` parameters can be removed by scaling:",
        f"{len(m.params)} parameters -> {an.min_params}. -/",
        f"theorem rank_Apar : Apar.rank = {an.param_rank} := by unfold Apar; eval_rank",
        "",
    ]

    if S_idx:
        AS = an.A[:, S_idx]
        out += [
            "/-- Columns of `A` for the normalized parameters "
            + ", ".join(map(str, nd.normalized))
            + ". -/",
            f"def AS : Matrix (Fin {r}) (Fin {len(S_idx)}) ℤ :=\n  {lean_matrix(AS)}",
            "",
            f"theorem AS_cols : AS = Amat.submatrix id {lean_fin_vec(S_idx)} := by decide +kernel",
            "",
            "/-- **Check 5.** These parameters can be set to 1 *simultaneously*: their columns are",
            "independent (Exercise 2 in `Exercises.lean`). -/",
            f"theorem rank_AS : AS.rank = {len(S_idx)} := by unfold AS; eval_rank",
            "",
        ]

    Vm = _integer_columns([nd.exponent_vector(x) for x in new_vars])
    cols_doc = ", ".join(f"{nd.new_symbol[x]}" for x in new_vars)
    if nd.fully_invariant():
        out += [
            f"/-- Exponent vectors of the new variables ({cols_doc}), one per column",
            "(each column scaled by a positive integer to clear denominators). -/",
            f"def Vmat : Matrix (Fin {n}) (Fin {len(new_vars)}) ℤ :=\n  {lean_matrix(Vm)}",
            "",
            "/-- **Check 6.** Every new variable is invariant under every scaling: it is dimensionless. -/",
            "theorem new_vars_invariant : Amat * Vmat = 0 := by decide +kernel",
            "",
        ]
    else:
        out += [
            f"/-- Exponent vectors of the new variables ({cols_doc}). -/",
            f"def Vmat : Matrix (Fin {n}) (Fin {len(new_vars)}) ℤ :=\n  {lean_matrix(Vm)}",
            "",
            "/-- The subgroup of scalings actually used for the reduction. -/",
            f"def A1mat : Matrix (Fin {nd.A1.shape[0]}) (Fin {n}) ℤ :=\n  {lean_matrix(nd.A1)}",
            "",
            "/-- **Check 6 (weaker).** New variables are invariant under the scalings used.",
            "Some residual scalings act only on time/states, so not every new variable is",
            "dimensionless. -/",
            "theorem new_vars_invariant : A1mat * Vmat = 0 := by decide +kernel",
            "",
        ]
    # Change of variables: (new variables, normalized params) as log-coordinates is invertible.
    T = (
        Vm.row_join(sp.Matrix([[1 if i == j else 0 for j in S_idx] for i in range(n)]))
        if S_idx
        else Vm
    )
    out += [
        "/-- In log coordinates the change of variables (new variables, normalized parameters)",
        "is a square matrix of full rank, so the substitution can be undone. -/",
        f"def Tmat : Matrix (Fin {n}) (Fin {T.shape[1]}) ℤ :=\n  {lean_matrix(T)}",
        "",
        f"/-- **Check 7.** The change of variables is invertible. -/",
        f"theorem change_of_variables_invertible : Tmat.rank = {n} := by unfold Tmat; eval_rank",
        "",
    ]

    # Chain-rule identities, only when all exponents are integers.
    if nd.integer_exponents():
        back = {nd.new_symbol[x]: nd.new_expr[x] for x in nd.new_expr}
        M_t = sp.simplify(nd.new_expr[m.t] / m.t)
        binders = " ".join(lean_name(v) for v in V)
        hyps = " ".join(f"(h_{lean_name(v)} : 0 < {lean_name(v)})" for v in V)
        for z, f, g in zip(m.states, m.rhs, nd.reduced_rhs):
            M_z = sp.simplify(nd.new_expr[z] / z)
            rhs = g.xreplace(back)
            haves = _denominator_haves(f, rhs)
            zh, th = nd.new_symbol[z], nd.new_symbol[m.t]
            out += [
                f"/-- **Check 8 ({z}).** Chain rule: `d{zh}/d{th} = ({M_z})/({M_t}) * d{z}/d{m.t}`",
                f"equals the reduced right-hand side `{g}` once the new variables are",
                "written out in the original ones. -/",
                f"theorem rhs_{z} ({binders} : ℝ)\n    {hyps} :\n"
                f"    {to_lean(M_z)} / {to_lean(M_t)} * {to_lean(f)} =\n    {to_lean(rhs)} := by{haves}\n  rhs_check",
                "",
            ]
    else:
        out += [
            "-- Check 8 skipped: some exponents are fractional (would need Real.rpow).",
            "",
        ]

    for i, c in enumerate(constraints, 1):
        out += _constraint_section(i, c, nd)

    out += [f"end NondimVerify.Cert.{module}", ""]
    return "\n".join(out)


def _constraint_section(
    i: int, c: ConstraintResult, nd: Nondimensionalization
) -> list[str]:
    """Lean theorems backing one constraint verdict (SAT or UNSAT)."""
    m, an = nd.model, nd.analysis
    n, r = len(m.variables), an.A.shape[0]
    keep = ", ".join(map(str, c.keep)) or "nothing"
    want = (
        "; wanting " + ", ".join(f"{k} = {v}" for k, v in c.want.items())
        if c.want
        else ""
    )
    verdict = "SATISFIABLE" if c.satisfiable else f"UNSATISFIABLE ({c.reason})"
    out = [
        f"/-! ### Constraint {i}: eliminate ≥ {c.eliminate_at_least}, keeping {keep}{want}",
        "",
        f"**{verdict}.** {c.explanation}",
        "-/",
        "",
    ]
    cols = [m.index(p) for p in c.candidates]
    if cols and r:
        enough = c.eliminate_at_least <= c.available_rank
        out += [
            "/-- Columns of `A` for the parameters we are allowed to normalize: "
            + ", ".join(map(str, c.candidates))
            + ". -/",
            f"def Acand{i} : Matrix (Fin {r}) (Fin {len(cols)}) ℤ :=\n  {lean_matrix(an.A[:, cols])}",
            "",
            f"theorem Acand{i}_cols : Acand{i} = Amat.submatrix id {lean_fin_vec(cols)} := by decide +kernel",
            "",
            f"/-- At most {c.available_rank} of the candidates can be removed. -/",
            f"theorem constraint{i}_rank : Acand{i}.rank = {c.available_rank} := by unfold Acand{i}; eval_rank",
            "",
            f"/-- The requested number ({c.eliminate_at_least}) is "
            + ("within reach." if enough else "out of reach: no scaling can do it.")
            + " -/",
            f"theorem constraint{i}_{'enough' if enough else 'unsat'} : "
            f"{c.eliminate_at_least} {'≤' if enough else '>'} Acand{i}.rank := by have h := constraint{i}_rank; omega",
            "",
        ]
    if c.reason in ("not_monomial", "not_parameter_only"):
        out += [
            f"-- No certificate: the solver rejects this request before any linear algebra ({c.reason}).",
            "",
        ]
    W = c.want_vectors
    if W is not None and W.shape[1]:
        k = W.shape[1]
        out += [
            "/-- Exponent vectors of the wanted groups (one per column, over all variables). -/",
            f"def Wmat{i} : Matrix (Fin {n}) (Fin {k}) ℤ :=\n  {lean_matrix(W)}",
            "",
        ]
        if c.reason == "not_invariant":
            out += [
                "/-- Some scaling moves a wanted group: it has units, so it cannot be a parameter of a",
                "dimensionless model. -/",
                f"theorem constraint{i}_want_not_invariant : Amat * Wmat{i} ≠ 0 := by decide +kernel",
                "",
            ]
        else:
            out += [
                "/-- The wanted groups are dimensionless. -/",
                f"theorem constraint{i}_want_invariant : Amat * Wmat{i} = 0 := by decide +kernel",
                "",
            ]
            rk = W.rank()
            out += [
                f"theorem constraint{i}_want_rank : Wmat{i}.rank = {rk} := by unfold Wmat{i}; eval_rank",
                "",
                "/-- The wanted groups are "
                + (
                    "independent."
                    if rk == k
                    else "NOT independent, so they cannot all be parameters."
                )
                + " -/",
                f"theorem constraint{i}_want_{'independent' if rk == k else 'dependent'} : "
                f"Wmat{i}.rank {'=' if rk == k else '<'} {k} := by have h := constraint{i}_want_rank; omega",
                "",
            ]
    g = c.regrouping
    if g is not None and g.M.shape[0]:
        nd = (
            c.witness
        )  # the regrouping rewrites the *witness* reduction, which may differ from the file's main one
        out += [
            "-- The witness for this constraint normalizes "
            + ", ".join(map(str, nd.normalized))
            + "; its reduced parameters are "
            + ", ".join(map(str, nd.reduced_params))
            + ".",
            "",
        ]
        q = g.M.shape[0]
        out += [
            "/-- Row `j` = exponents of group `j` over the reduced parameters; the first "
            f"{g.n_wanted} row(s) are the wanted groups. -/",
            f"def Mmat{i} : Matrix (Fin {q}) (Fin {q}) ℤ :=\n  {lean_matrix(g.M)}",
            "",
            "/-- The groups are a valid new set of parameters (the regrouping is invertible). -/",
            f"theorem constraint{i}_regroup_invertible : Mmat{i}.rank = {q} := by unfold Mmat{i}; eval_rank",
            "",
        ]
        if g.integer:
            out += [
                "/-- Integer inverse: the regrouping needs no fractional powers (unimodular). -/",
                f"def Minv{i} : Matrix (Fin {q}) (Fin {q}) ℤ :=\n  {lean_matrix(g.Minv)}",
                "",
                f"theorem constraint{i}_regroup_unimodular : Mmat{i} * Minv{i} = 1 := by decide +kernel",
                "",
            ]
            hat = {sym: in_hat for sym, _, in_hat in g.groups}
            free_syms = sorted(
                {x for e in nd.reduced_rhs for x in e.free_symbols}
                | {x for e in hat.values() for x in e.free_symbols},
                key=str,
            )
            binders = " ".join(lean_name(v) for v in free_syms)
            hyps = " ".join(
                f"(h_{lean_name(v)} : 0 < {lean_name(v)})" for v in free_syms
            )
            for z, old, new in zip(m.states, nd.reduced_rhs, g.reduced_rhs):
                out += [
                    f"/-- The regrouped equation for `{nd.new_symbol[z]}` is the same equation, rewritten. -/",
                    f"theorem constraint{i}_regroup_{z} ({binders} : ℝ)\n    {hyps} :\n"
                    f"    {to_lean(old)} =\n    {to_lean(new.xreplace(hat))} := by{_denominator_haves(old, new.xreplace(hat))}\n  rhs_check",
                    "",
                ]
        else:
            out += [
                "-- Regrouped equations not exported: they need fractional powers (Real.rpow).",
                "",
            ]
    return out


_LEAN_RESERVED = {
    "at",
    "in",
    "fun",
    "from",
    "have",
    "show",
    "let",
    "if",
    "then",
    "else",
    "do",
    "by",
    "end",
    "open",
    "at",
    "with",
    "match",
    "def",
    "theorem",
    "import",
    "where",
    "forall",
    "exists",
    "Type",
    "Prop",
}


def lean_name(v) -> str:
    """A model symbol as a Lean identifier (reserved words get a trailing underscore)."""
    name = str(v)
    return name + "_" if name in _LEAN_RESERVED else name


def _denominator_haves(*exprs) -> str:
    """`have : d ≠ 0 := by positivity` lines for every non-trivial denominator, so `field_simp` can clear it."""
    dens = set()
    for e in exprs:
        for d in sp.Mul.make_args(sp.factor(sp.denom(sp.together(e)))):
            if not d.is_Symbol and not d.is_number:
                dens.add(d.base if d.is_Pow else d)
    return "".join(
        f"\n  have : {to_lean(d)} ≠ 0 := by positivity" for d in sorted(dens, key=str)
    )


def write_certificate(nd, path: Path, constraints=(), module=None) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(certificate(nd, constraints, module))
    return path
